"""Build compact, lazily decoded addon data from the verified Forever listing.

--inventory is an optional read-only template snapshot with keys revision, items
(IDs), displayIDs, creatures ([entry, npcflags, [[displayID, scale], ...]]).
It enriches the whitelist; it never adds an ID to the catalog.
"""
import argparse
import gzip
import hashlib
import html
import json
from pathlib import Path


def clean(value):
    return " ".join(html.unescape(str(value or "")).split())


def build(snapshot, inventory=None):
    if snapshot["tree"] != 16:
        raise ValueError("Only Forever (tree 16) is accepted")
    inventory = inventory or {}
    creatures = {r[0]: r for r in inventory.get("creatures", [])}
    displays = set(inventory.get("displayIDs", []))
    item_ids = set(inventory.get("items", []))
    rows = {"items": [], "creatures": []}
    coverage = {"itemsMissingInReference": [], "creaturesMissingInReference": [], "creaturesWithDisplay": 0}
    for kind, source in (("items", snapshot["items"]), ("creatures", snapshot["npcs"])):
        if len({r["id"] for r in source}) != len(source):
            raise ValueError("Duplicate catalog IDs")
        for entry in sorted(source, key=lambda r: (clean(r["name"]).lower(), r["id"])):
            id = entry["id"]
            if not isinstance(id, int) or id <= 0:
                raise ValueError("Invalid entry ID")
            name = clean(entry["displayName"] or entry["name"])
            if kind == "items":
                present = id in item_ids
                fields = [id, name, entry.get("quality", 1), entry.get("classs", 0),
                    entry.get("subclass", 0), entry.get("slot", 0), entry.get("level", 0),
                    entry.get("reqlevel", 0), entry.get("displayid", 0), entry.get("icon", ""),
                    entry.get("modelviewer", {}).get("displayid", 0), int(present) if inventory else -1]
                if inventory and not present: coverage["itemsMissingInReference"].append(id)
            else:
                record = creatures.get(id, [id, 0, []])
                models = list(dict.fromkeys(d for d, _ in record[2] if d in displays and d > 0))
                if models: coverage["creaturesWithDisplay"] += 1
                if inventory and id not in creatures: coverage["creaturesMissingInReference"].append(id)
                fields = [id, name, entry.get("type", 10), entry.get("classification", 0),
                    entry.get("minlevel", 0), entry.get("maxlevel", 0), clean(entry.get("tag")),
                    record[1], ",".join(map(str, models)), int(id in creatures) if inventory else -1]
            rows[kind].append("\t".join(map(str, fields)))
    date = snapshot["collected"][:10]
    revision = inventory.get("revision", "not-provided")
    lines = ["-- Generated by tools/generate_catalog.py; factual Forever metadata only.",
        "-- Whitelist: https://www.wowhead.com/forever/database (tree 16).",
        "GMGenie.CatalogData = {", f'    date="{date}", tree=16, referenceRevision="{revision}",',
        f'    counts={{items={len(rows["items"])},creatures={len(rows["creatures"])} }},', "    chunks={"]
    for kind in rows:
        lines.append(f"        {kind}={{")
        for i in range(0, len(rows[kind]), 512):
            text = "\n".join(rows[kind][i:i+512])
            if "]=]" in text: raise ValueError("Unsafe long-string delimiter")
            lines.append("[=[" + text + "]=],")
        lines.append("        },")
    lines.extend(["    }", "};", ""])
    lua = "\n".join(lines)
    ledger = {"date": date, "tree": 16, "referenceRevision": revision,
        "counts": {kind: len(values) for kind, values in rows.items()}, "coverage": coverage,
        "catalogSHA256": hashlib.sha256(lua.encode()).hexdigest(), "sources": snapshot["sources"],
        "limitations": ["Availability refers to the reference snapshot, not a live query of the user's server.",
            "Missing appearances fall back to client creature queries or an explanatory message.",
            "The reference inventory unions DB2 and SQL records; runtime hotfix deletes are not evaluated."]}
    return lua, ledger


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("snapshot", type=Path)
    parser.add_argument("--inventory", type=Path)
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    snapshot = json.loads(args.snapshot.read_text(encoding="utf-8"))
    inventory = None
    if args.inventory:
        opener = gzip.open if args.inventory.suffix == ".gz" else open
        with opener(args.inventory, "rt", encoding="utf-8") as stream: inventory = json.load(stream)
    lua, ledger = build(snapshot, inventory)
    (args.output / "CatalogData.lua").write_bytes(lua.encode("utf-8"))
    (args.output / "docs" / "catalog-sources.json").write_text(json.dumps(ledger, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"counts": ledger["counts"], "modelCoverage": ledger["coverage"]["creaturesWithDisplay"],
                      "bytes": len(lua.encode())}))


if __name__ == "__main__":
    main()
